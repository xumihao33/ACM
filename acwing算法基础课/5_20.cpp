#include<iostream>
using namespace std;

const int N = 100010, M = 1000010;

int n, m;
char p[N], s[M];   // p 模式串（较短）, s 主串（较长）
int ne[N];          // ne[j] = next[j], 即 p[1~j] 的最长相等前后缀长度

int main()
{
    // ========== 输入 ==========
    // AcWing 格式：第一行是模式串长度和内容，第二行是主串长度和内容
    // 下标从 1 开始，这样 ne[j] 存的长度可以直接作为下标使用
    cin >> n >> p + 1;    // p[1] ~ p[n]
    cin >> m >> s + 1;    // s[1] ~ s[m]

    // ========== 1. 求 next 数组 ==========
    // 本质：用模式串自己匹配自己
    // ne[1] = 0，因为单个字符没有真前后缀
    for (int i = 2, j = 0; i <= n; i ++ )  // i 从 2 开始（从第 2 个字符求 next）
    {
        // 失配：j 不断回退到 next[j]，直到匹配或退到 0
        while (j && p[i] != p[j + 1]) j = ne[j];

        // 匹配成功：j 可以往后走一位
        if (p[i] == p[j + 1]) j ++ ;

        // 记录 next[i]
        ne[i] = j;
    }

    // ========== 2. KMP 匹配 ==========
    // i 遍历主串 s，j 指向模式串 p 中当前已匹配到的位置
    for (int i = 1, j = 0; i <= m; i ++ )
    {
        // 失配：j 回退到 next[j]
        // 含义：p[1~j] 已经匹配上了，但 p[j+1] != s[i]
        //       把 j 跳到 next[j]，相当于用模式串的已匹配后缀对齐前缀
        while (j && s[i] != p[j + 1]) j = ne[j];

        // 匹配成功：j 后移
        if (s[i] == p[j + 1]) j ++ ;

        // 完全匹配：j == n 意味着模式串全部匹配
        if (j == n)
        {
            // 输出匹配起始位置（因为下标从 1 开始）
            // i - n + 1 = 当前主串位置 - 模式串长度 + 1
            printf("%d ", i - n + 1);

            // 继续找下一个匹配：回退 j，相当于把已匹配的部分当成"后缀"再利用
            j = ne[j];
        }
    }

    return 0;
}